#!/usr/bin/env python3
"""Sign and package STM32 OTA releases for the ESP8266 gateway."""

from __future__ import annotations

import argparse
import base64
import binascii
import hashlib
import json
import os
import re
import shutil
import struct
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, utils


APP_MAX_SIZE = 0x37000
TARGET = "hood-stm32f103rc-v1"
METADATA_MAGIC = 0x4F54414D
METADATA_FORMAT = 1
METADATA_VALID = 0x56414C44
METADATA_A_ADDRESS = 0x0803F000
METADATA_B_ADDRESS = 0x0803F800


def canonical_manifest(version_code: int, size: int, sha256_hex: str) -> bytes:
    return f"hood-ota-v1\n{TARGET}\n{version_code}\n{size}\n{sha256_hex}\n".encode("ascii")


def public_key_bytes(private_key: ec.EllipticCurvePrivateKey) -> bytes:
    numbers = private_key.public_key().public_numbers()
    return numbers.x.to_bytes(32, "big") + numbers.y.to_bytes(32, "big")


def emit_public_header(path: Path, key_bytes: bytes) -> None:
    rows = []
    for offset in range(0, len(key_bytes), 8):
        rows.append("    " + ", ".join(f"0x{value:02X}" for value in key_bytes[offset:offset + 8]) + ",")
    content = """#ifndef __OTA_PUBLIC_KEY_H
#define __OTA_PUBLIC_KEY_H

#include <stdint.h>

/* Generated by tools/release_firmware.py; SEC1 x||y, big-endian. */
static const uint8_t g_ota_signing_public_key[64] = {
%s
};

#endif /* __OTA_PUBLIC_KEY_H */
""" % "\n".join(rows)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="ascii")


def load_private_key(path: Path) -> ec.EllipticCurvePrivateKey:
    key = serialization.load_pem_private_key(path.read_bytes(), password=None)
    if not isinstance(key, ec.EllipticCurvePrivateKey) or not isinstance(key.curve, ec.SECP256R1):
        raise ValueError("signing key must be an unencrypted ECDSA P-256 private key")
    return key


def command_keygen(args: argparse.Namespace) -> int:
    private_path = Path(args.private_key)
    if private_path.exists() and not args.force:
        raise FileExistsError(f"refusing to overwrite {private_path}; pass --force intentionally")
    private_path.parent.mkdir(parents=True, exist_ok=True)
    private_key = ec.generate_private_key(ec.SECP256R1())
    private_path.write_bytes(private_key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    ))
    emit_public_header(Path(args.public_header), public_key_bytes(private_key))
    print(f"private key: {private_path}")
    print(f"public header: {args.public_header}")
    print("Rebuild and reflash the bootloader after changing the public key.")
    return 0


def check_application_version(config_path: Path, version_code: int) -> None:
    text = config_path.read_text(encoding="utf-8")
    match = re.search(r"#define\s+OTA_APP_VERSION_CODE\s+(\d+)(?:UL)?", text)
    if not match:
        raise ValueError(f"OTA_APP_VERSION_CODE not found in {config_path}")
    compiled_version = int(match.group(1))
    if compiled_version != version_code:
        raise ValueError(
            f"application embeds version {compiled_version}, release requested {version_code}; "
            "update ota_config.h and rebuild first"
        )


def build_factory_metadata(version_code: int, image: bytes, digest: bytes, signature: bytes) -> bytes:
    prefix = struct.pack(
        "<6I32s64s",
        METADATA_MAGIC,
        METADATA_FORMAT,
        1,
        METADATA_VALID,
        version_code,
        len(image),
        digest,
        signature,
    )
    assert len(prefix) == 120
    crc = binascii.crc32(prefix) & 0xFFFFFFFF
    return prefix + struct.pack("<II", crc, 0xFFFFFFFF)


def ihex_record(address: int, record_type: int, data: bytes) -> str:
    body = bytes((len(data), (address >> 8) & 0xFF, address & 0xFF, record_type)) + data
    checksum = (-sum(body)) & 0xFF
    return ":" + (body + bytes((checksum,))).hex().upper()


def data_ihex(address: int, data: bytes) -> str:
    lines = []
    current_upper = None
    for offset in range(0, len(data), 16):
        absolute = address + offset
        upper = absolute >> 16
        if upper != current_upper:
            lines.append(ihex_record(0, 4, struct.pack(">H", upper)))
            current_upper = upper
        lines.append(ihex_record(absolute & 0xFFFF, 0, data[offset:offset + 16]))
    lines.append(ihex_record(0, 1, b""))
    return "\n".join(lines) + "\n"


def without_ihex_eof(path: Path) -> list[str]:
    return [line.strip() for line in path.read_text(encoding="ascii").splitlines()
            if line.strip() and not line.upper().startswith(":00000001")]


def command_release(args: argparse.Namespace) -> int:
    binary_path = Path(args.binary)
    image = binary_path.read_bytes()
    if not image or len(image) > APP_MAX_SIZE:
        raise ValueError(f"application size {len(image)} is outside 1..{APP_MAX_SIZE} bytes")
    if args.version_code <= 0:
        raise ValueError("version-code must be positive and monotonically increasing")
    if not args.base_url.lower().startswith("https://"):
        raise ValueError("base-url must use HTTPS")

    check_application_version(Path(args.config), args.version_code)
    private_key = load_private_key(Path(args.private_key))
    digest = hashlib.sha256(image).digest()
    digest_hex = digest.hex()
    canonical = canonical_manifest(args.version_code, len(image), digest_hex)
    der_signature = private_key.sign(canonical, ec.ECDSA(hashes.SHA256()))
    r_value, s_value = utils.decode_dss_signature(der_signature)
    signature = r_value.to_bytes(32, "big") + s_value.to_bytes(32, "big")
    if len(signature) != 64:
        raise AssertionError("unexpected ECDSA signature size")

    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)
    firmware_name = f"stm32-{args.version}.bin"
    firmware_path = output_dir / firmware_name
    shutil.copyfile(binary_path, firmware_path)
    manifest = {
        "schema": 1,
        "target": TARGET,
        "version": args.version,
        "version_code": args.version_code,
        "size": len(image),
        "sha256": digest_hex,
        "signature": base64.b64encode(signature).decode("ascii"),
        "url": args.base_url.rstrip("/") + "/" + firmware_name,
    }
    manifest_temp = output_dir / "manifest.json.tmp"
    manifest_path = output_dir / "manifest.json"
    manifest_temp.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.replace(manifest_temp, manifest_path)
    metadata = build_factory_metadata(args.version_code, image, digest, signature)
    metadata_path = output_dir / "factory_metadata.bin"
    metadata_path.write_bytes(metadata)
    metadata_hex_path = output_dir / "factory_metadata.hex"
    metadata_hex_path.write_text(data_ihex(METADATA_A_ADDRESS, metadata), encoding="ascii")

    # Explicitly invalidate metadata page B in the factory image. Merely
    # programming page A does not erase B when the programmer uses
    # sector-based erase, so a higher-generation PENDING record from an
    # interrupted OTA could otherwise override the new factory metadata.
    metadata_b_clear = bytes(128)
    metadata_b_clear_path = output_dir / "factory_metadata_b_clear.bin"
    metadata_b_clear_path.write_bytes(metadata_b_clear)
    metadata_b_clear_hex_path = output_dir / "factory_metadata_b_clear.hex"
    metadata_b_clear_hex_path.write_text(
        data_ihex(METADATA_B_ADDRESS, metadata_b_clear),
        encoding="ascii",
    )

    bootloader_hex = Path(args.bootloader_hex)
    application_hex = Path(args.application_hex)
    if bootloader_hex.exists() and application_hex.exists():
        bundle_lines = without_ihex_eof(bootloader_hex)
        bundle_lines.extend(without_ihex_eof(application_hex))
        bundle_lines.extend(without_ihex_eof(metadata_hex_path))
        bundle_lines.extend(without_ihex_eof(metadata_b_clear_hex_path))
        bundle_lines.append(":00000001FF")
        (output_dir / "factory_bundle.hex").write_text("\n".join(bundle_lines) + "\n", encoding="ascii")

    print(f"firmware: {firmware_path} ({len(image)} bytes)")
    print(f"manifest: {manifest_path}")
    print(f"factory metadata: {metadata_path} -> flash at 0x0803F000")
    print(f"factory metadata B clear: {metadata_b_clear_path} -> flash at 0x0803F800")
    print(f"sha256: {digest_hex}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    keygen = commands.add_parser("keygen", help="generate a private key and matching bootloader header")
    keygen.add_argument("--private-key", default="Release/private_key.pem")
    keygen.add_argument("--public-header", default="Common/ota_public_key.h")
    keygen.add_argument("--force", action="store_true")
    keygen.set_defaults(function=command_keygen)

    release = commands.add_parser("release", help="sign and package an application binary")
    release.add_argument("--binary", default="Objects/Project.bin")
    release.add_argument("--private-key", default="Release/private_key.pem")
    release.add_argument("--config", default="Common/ota_config.h")
    release.add_argument("--output", default="Release/firmware")
    release.add_argument("--bootloader-hex", default="Bootloader/Objects/Bootloader.hex")
    release.add_argument("--application-hex", default="Objects/Project.hex")
    release.add_argument("--version", required=True)
    release.add_argument("--version-code", required=True, type=int)
    release.add_argument("--base-url", required=True)
    release.set_defaults(function=command_release)
    return parser


def main() -> int:
    try:
        args = build_parser().parse_args()
        return args.function(args)
    except Exception as error:
        print(f"release error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
